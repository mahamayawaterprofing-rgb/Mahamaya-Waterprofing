-- Mahamaya Waterproofing: bookings table and Row Level Security
-- Supabase SQL Editor में चलाएँ। Admin email को अपने वास्तविक Auth email से मिलाएँ।

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  mobile text not null,
  address text not null,
  problem text not null,
  square_feet numeric,
  booking_status text not null default 'Pending',
  created_at timestamptz not null default now()
);

alter table public.bookings add column if not exists customer_name text;
alter table public.bookings add column if not exists mobile text;
alter table public.bookings add column if not exists address text;
alter table public.bookings add column if not exists problem text;
alter table public.bookings add column if not exists square_feet numeric;
alter table public.bookings add column if not exists booking_status text default 'Pending';
alter table public.bookings add column if not exists created_at timestamptz default now();

alter table public.bookings enable row level security;

-- पुरानी इसी नाम की policies हटाकर साफ policies बनाएँ।
drop policy if exists "Admin View Bookings" on public.bookings;
drop policy if exists "Allow Public Booking" on public.bookings;
drop policy if exists "Mahamaya Public Booking Insert" on public.bookings;
drop policy if exists "Mahamaya Admin Read" on public.bookings;
drop policy if exists "Mahamaya Admin Update" on public.bookings;

create policy "Mahamaya Public Booking Insert"
on public.bookings for insert
to anon, authenticated
with check (true);

create policy "Mahamaya Admin Read"
on public.bookings for select
to authenticated
using ((auth.jwt() ->> 'email') = 'mahamayawaterproofing@gmail.com');

create policy "Mahamaya Admin Update"
on public.bookings for update
to authenticated
using ((auth.jwt() ->> 'email') = 'mahamayawaterproofing@gmail.com')
with check ((auth.jwt() ->> 'email') = 'mahamayawaterproofing@gmail.com');

-- ध्यान दें: anon/public key वेबसाइट में लगाएँ; service_role/secret key कभी HTML में न डालें।
